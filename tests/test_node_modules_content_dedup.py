"""Tests for scripts.node_modules_content_dedup — pure logic + fs behavior on tmp dirs.
No DB, no network. Safe under the repo's no-prod-DB pytest guard (imports nothing DB-backed)."""
import os
import pathlib

import pytest

from scripts import node_modules_content_dedup as nmd


def _write(path: pathlib.Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content)


# ---- content_key -------------------------------------------------------------
def test_content_key_same_content_same_key(tmp_path):
    a = tmp_path / "a.txt"
    b = tmp_path / "b.txt"
    _write(a, b"hello world")
    _write(b, b"hello world")
    assert nmd.content_key(a) == nmd.content_key(b)


def test_content_key_different_content_different_key(tmp_path):
    a = tmp_path / "a.txt"
    b = tmp_path / "b.txt"
    _write(a, b"hello world")
    _write(b, b"goodbye world")
    assert nmd.content_key(a) != nmd.content_key(b)


def test_content_key_different_size_short_circuits_without_full_hash(tmp_path, monkeypatch):
    # size mismatch alone must distinguish keys even if hashing were skipped
    a = tmp_path / "a.txt"
    b = tmp_path / "b.txt"
    _write(a, b"x")
    _write(b, b"xx")
    ka, kb = nmd.content_key(a), nmd.content_key(b)
    assert ka[0] != kb[0]
    assert ka != kb


# ---- scan_node_modules_files ---------------------------------------------------
def test_scan_finds_files_under_node_modules_only(tmp_path):
    wt = tmp_path / "wt1"
    _write(wt / "node_modules" / "pkg" / "index.js", b"content")
    _write(wt / "src" / "app.js", b"not under node_modules")
    found = list(nmd.scan_node_modules_files([wt]))
    assert any(p.name == "index.js" for p in found)
    assert not any(p.name == "app.js" for p in found)


def test_scan_skips_symlinks(tmp_path):
    wt = tmp_path / "wt1"
    real = wt / "node_modules" / "pkg" / "real.js"
    _write(real, b"content")
    link = wt / "node_modules" / "pkg" / "link.js"
    os.symlink(real, link)
    found = list(nmd.scan_node_modules_files([wt]))
    names = {p.name for p in found}
    assert "real.js" in names
    assert "link.js" not in names


def test_scan_multiple_roots(tmp_path):
    wt1 = tmp_path / "wt1"
    wt2 = tmp_path / "wt2"
    _write(wt1 / "node_modules" / "pkg" / "index.js", b"content")
    _write(wt2 / "node_modules" / "pkg" / "index.js", b"content")
    found = list(nmd.scan_node_modules_files([wt1, wt2]))
    assert len(found) == 2


# ---- group_by_content ----------------------------------------------------------
def test_group_by_content_groups_identical_files(tmp_path):
    wt1 = tmp_path / "wt1"
    wt2 = tmp_path / "wt2"
    f1 = wt1 / "node_modules" / "pkg" / "index.js"
    f2 = wt2 / "node_modules" / "pkg" / "index.js"
    _write(f1, b"same content")
    _write(f2, b"same content")
    files = list(nmd.scan_node_modules_files([wt1, wt2]))
    groups = nmd.group_by_content(files)
    assert len(groups) == 1
    (key, paths), = groups.items()
    assert set(paths) == {f1, f2}


def test_group_by_content_singletons_excluded(tmp_path):
    wt1 = tmp_path / "wt1"
    f1 = wt1 / "node_modules" / "pkg" / "unique.js"
    _write(f1, b"only one")
    files = list(nmd.scan_node_modules_files([wt1]))
    groups = nmd.group_by_content(files, min_group_size=2)
    assert groups == {}


def test_scan_min_size_filters_small_files(tmp_path):
    wt = tmp_path / "wt1"
    small = wt / "node_modules" / "pkg" / "small.js"
    big = wt / "node_modules" / "pkg" / "big.js"
    _write(small, b"x" * 100)
    _write(big, b"x" * 5000)
    found = list(nmd.scan_node_modules_files([wt], min_size=4096))
    names = {p.name for p in found}
    assert "big.js" in names
    assert "small.js" not in names


# ---- dedup_group (the hardlinking core) ----------------------------------------
def test_dedup_group_dry_run_changes_nothing(tmp_path):
    f1 = tmp_path / "a" / "x.js"
    f2 = tmp_path / "b" / "x.js"
    _write(f1, b"dup")
    _write(f2, b"dup")
    before_inode1, before_inode2 = f1.stat().st_ino, f2.stat().st_ino
    rep = nmd.dedup_group([f1, f2], dry_run=True, min_age_s=0)
    assert rep["would_link"] == 1
    assert f1.stat().st_ino == before_inode1
    assert f2.stat().st_ino == before_inode2


def test_dedup_group_apply_hardlinks_to_canonical(tmp_path):
    f1 = tmp_path / "a" / "x.js"
    f2 = tmp_path / "b" / "x.js"
    _write(f1, b"dup")
    _write(f2, b"dup")
    rep = nmd.dedup_group([f1, f2], dry_run=False, min_age_s=0)
    assert rep["linked"] == 1
    assert rep["errors"] == []
    # f2 now shares f1's inode (same file on disk)
    assert f1.stat().st_ino == f2.stat().st_ino
    # content is untouched
    assert f1.read_bytes() == b"dup"
    assert f2.read_bytes() == b"dup"


def test_dedup_group_already_hardlinked_is_noop(tmp_path):
    f1 = tmp_path / "a" / "x.js"
    _write(f1, b"dup")
    f2 = tmp_path / "b" / "x.js"
    f2.parent.mkdir(parents=True, exist_ok=True)
    os.link(f1, f2)
    rep = nmd.dedup_group([f1, f2], dry_run=False)
    assert rep["linked"] == 0
    assert rep["already_linked"] == 1


def test_dedup_group_verifies_content_before_each_link(tmp_path):
    """Defense in depth: even within a pre-computed group, re-verify byte-identical
    content immediately before linking (a file could have changed between scan and
    apply, e.g. a fresh install landing mid-run) -- never trust a stale group blindly."""
    f1 = tmp_path / "a" / "x.js"
    f2 = tmp_path / "b" / "x.js"
    _write(f1, b"dup")
    _write(f2, b"dup")
    # mutate f2 AFTER grouping, simulating a race
    f2.write_bytes(b"CHANGED")
    rep = nmd.dedup_group([f1, f2], dry_run=False, min_age_s=0)
    assert rep["linked"] == 0
    assert any("content changed" in e.lower() or "mismatch" in e.lower() for e in rep["errors"])
    assert f2.read_bytes() == b"CHANGED"  # untouched, not clobbered


def test_dedup_group_skips_file_modified_too_recently(tmp_path, monkeypatch):
    """A file written in the last few minutes could be an in-progress install --
    don't link it yet even if content currently matches (could still be growing)."""
    f1 = tmp_path / "a" / "x.js"
    f2 = tmp_path / "b" / "x.js"
    _write(f1, b"dup")
    _write(f2, b"dup")
    rep = nmd.dedup_group([f1, f2], dry_run=False, min_age_s=10_000_000)
    assert rep["linked"] == 0
    assert rep["skipped_too_recent"] == 1


# ---- any_install_running (coarse safety gate) ----------------------------------
def test_any_install_running_true_when_matching_process(monkeypatch):
    def fake_ps_output():
        return "sheikhmusa  1234   0.0  0.1 node /usr/local/bin/npm install\n"
    monkeypatch.setattr(nmd, "_ps_snapshot", fake_ps_output)
    assert nmd.any_install_running() is True


def test_any_install_running_false_when_no_matching_process(monkeypatch):
    def fake_ps_output():
        return "sheikhmusa  1234   0.0  0.1 /bin/zsh -i\n"
    monkeypatch.setattr(nmd, "_ps_snapshot", fake_ps_output)
    assert nmd.any_install_running() is False


# ---- end-to-end sweep -----------------------------------------------------------
def test_sweep_detect_only_reports_savings_without_touching(tmp_path, monkeypatch):
    monkeypatch.setattr(nmd, "any_install_running", lambda: False)
    wt1, wt2 = tmp_path / "wt1", tmp_path / "wt2"
    _write(wt1 / "node_modules" / "pkg" / "big.js", b"x" * 1000)
    _write(wt2 / "node_modules" / "pkg" / "big.js", b"x" * 1000)
    summary = nmd.sweep([wt1, wt2], dry_run=True, min_age_s=0, min_size=0)
    assert summary["would_free_bytes"] == 1000
    assert wt1.joinpath("node_modules", "pkg", "big.js").stat().st_ino != \
        wt2.joinpath("node_modules", "pkg", "big.js").stat().st_ino


def test_sweep_apply_frees_real_bytes(tmp_path, monkeypatch):
    monkeypatch.setattr(nmd, "any_install_running", lambda: False)
    wt1, wt2 = tmp_path / "wt1", tmp_path / "wt2"
    _write(wt1 / "node_modules" / "pkg" / "big.js", b"x" * 1000)
    _write(wt2 / "node_modules" / "pkg" / "big.js", b"x" * 1000)
    summary = nmd.sweep([wt1, wt2], dry_run=False, min_age_s=0, min_size=0)
    assert summary["freed_bytes"] == 1000
    assert summary["errors"] == []


def test_sweep_refuses_when_install_in_progress(tmp_path, monkeypatch):
    monkeypatch.setattr(nmd, "any_install_running", lambda: True)
    wt1 = tmp_path / "wt1"
    _write(wt1 / "node_modules" / "pkg" / "x.js", b"x")
    summary = nmd.sweep([wt1], dry_run=True, min_size=0)
    assert summary["skipped_install_in_progress"] is True
    assert summary["would_free_bytes"] == 0
