def test_lookup_error_does_not_poison_callers_transaction(pg_dsn):
    """A table missing subject/body (old fixture shape) makes the lookup fail; the caller's
    transaction must stay usable for its next checks."""
    with psycopg.connect(pg_dsn, autocommit=True) as conn:
        conn.execute("DROP SCHEMA public CASCADE")
        conn.execute("CREATE SCHEMA public")
        conn.execute("CREATE TABLE agent_messages (id bigint, to_agent text, thread_id uuid, "
                     "from_agent text, created_at timestamptz)")
    with psycopg.connect(pg_dsn) as conn:
        assert R.replied_row_ids(conn, [1]) == set()
        assert conn.execute("SELECT 1").fetchone() == (1,)
