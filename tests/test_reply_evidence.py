def _msg(dsn, frm, to, *, thread=None, subject="", body="", ago_s=0):
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute(
            "INSERT INTO agent_messages (from_agent, to_agent, thread_id, subject, body, created_at) "
            "VALUES (%s, %s, %s, %s, %s, now() - make_interval(secs => %s)) RETURNING id",
            (frm, to, thread, subject, body, ago_s))
        mid = cur.fetchone()[0]
        conn.commit()
        return mid


def _replied(dsn, ids):
    with psycopg.connect(dsn) as conn:
        return R.replied_row_ids(conn, ids)


# ── the helper ────────────────────────────────────────────────────────────────

def test_same_thread_reply_from_base_id_counts(db):
    """80345 shape: addressed to the instance, answered as the base, same thread."""
    row = _msg(db, "orch-console", "cc-cosem-adcda-1", thread=T1, ago_s=600)
    _msg(db, "cc-cosem-adcda", "orch-console", thread=T1, body="ack, on it", ago_s=60)
    assert _replied(db, [row]) == {row}


def test_cite_in_other_thread_counts(db):
    """80362 shape: answered as the instance, a different thread, citing #<id>."""
    row = _msg(db, "orch-console", "cc-cosem-adcda-3", thread=T1, ago_s=600)
    _msg(db, "cc-cosem-adcda-3", "cc-quality", thread=T2,
         subject=f"ruling from #{row} implemented, review please", ago_s=60)
    assert _replied(db, [row]) == {row}


def test_uncited_new_thread_does_not_count(db):
    """80021 shape: chatty replies to the sender, new threads, no cite -> still a page."""
    row = _msg(db, "orch-console", "cc-wingmen-sites-1", thread=T1, ago_s=600)
    _msg(db, "cc-wingmen-sites", "orch-console", thread=T2, subject="Phase 1 status", ago_s=60)
    assert _replied(db, [row]) == set()


