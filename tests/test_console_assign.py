def _fetch_bus_rows(dsn, to_agent):
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT id, from_agent, to_agent, thread_id, message_type, subject, body, "
            "priority, requires_response, is_test FROM agent_messages WHERE to_agent=%s",
            (to_agent,))
        return cur.fetchall()


def test_assign_without_source_msg_id_posts_bus_row_only(db):
    new_id = ca.assign("cc-cosem-platform-1", "do the thing", "P2")
    rows = _fetch_bus_rows(db, "cc-cosem-platform-1")
    assert len(rows) == 1 and rows[0][0] == new_id
    _, from_agent, to_agent, thread_id, mtype, subject, body, priority, req, is_test = rows[0]
    assert from_agent == "orch-console" and to_agent == "cc-cosem-platform-1"
    assert mtype == "decision" and priority == "P2" and req is True and is_test is False
    assert "do the thing" in body

    with psycopg.connect(db) as conn, conn.cursor() as cur:
        cur.execute("SELECT count(*) FROM operator_asks")
        assert cur.fetchone()[0] == 0, "a pure delegation (no source_msg_id) must never touch operator_asks"


def test_assign_with_source_msg_id_links_operator_asks_same_thread(db):
    new_id = ca.assign("cc-cosem-platform-1", "do the thing", "P1", source_msg_id=555)
    rows = _fetch_bus_rows(db, "cc-cosem-platform-1")
    assert rows[0][0] == new_id
    bus_thread = rows[0][3]

    with psycopg.connect(db) as conn, conn.cursor() as cur:
        cur.execute("SELECT thread_id, delegated_to, triage_state FROM operator_asks "
                    "WHERE source_msg_id=555 AND ask='do the thing'")
        row = cur.fetchone()
    assert row is not None
    assert row[0] == bus_thread, "operator_asks must link the SAME thread_id as the bus row"
    assert row[1] == "cc-cosem-platform-1" and row[2] == "ask"


def test_retry_same_source_msg_id_and_ask_links_not_duplicates(db):
    ca.assign("cc-cosem-platform-1", "do the thing", "P2", source_msg_id=777)
    ca.assign("cc-cosem-platform-1", "do the thing", "P2", source_msg_id=777)
    with psycopg.connect(db) as conn, conn.cursor() as cur:
        cur.execute("SELECT count(*) FROM operator_asks WHERE source_msg_id=777")
        assert cur.fetchone()[0] == 1, "a retry must LINK the existing row, not duplicate it"


def test_unknown_agent_exits_2(db):
    with pytest.raises(SystemExit) as exc:
        ca.assign("cc-does-not-exist", "do the thing", "P2")
    assert exc.value.code == 2


def test_operator_asks_failure_rolls_back_the_bus_row_too(db):
    """The actual atomicity proof: if the operator_asks write fails, the bus row from
    the SAME call must not survive either -- no orphan bus row."""
    with psycopg.connect(db, autocommit=True) as conn, conn.cursor() as cur:
        cur.execute("DROP TABLE operator_asks")

    with pytest.raises(Exception):
        ca.assign("cc-cosem-platform-1", "do the thing", "P1", source_msg_id=42)

    rows = _fetch_bus_rows(db, "cc-cosem-platform-1")
    assert rows == [], "operator_asks insert failed -- the bus row must have rolled back too"


def test_assign_uses_the_rpc_not_a_raw_insert(db, monkeypatch):
    """Gate-compliance proof (backlog#124): the write must go through
    post_agent_message(), never a raw INSERT INTO agent_messages, so the enforce-in-code
    gate (and eventually migration 120's revoke) sees this script as compliant."""
    calls = []
    real_execute = psycopg.Cursor.execute

    def spy_execute(self, query, *a, **kw):
        q = query if isinstance(query, str) else str(query)
        calls.append(q)
        return real_execute(self, query, *a, **kw)

    monkeypatch.setattr(psycopg.Cursor, "execute", spy_execute)
    ca.assign("cc-cosem-platform-1", "do the thing", "P2")
    joined = "\n".join(calls).lower()
    assert "insert into agent_messages" not in joined
    assert "post_agent_message" in joined
