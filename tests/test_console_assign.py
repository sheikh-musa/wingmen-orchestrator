"""console_assign.py — the console's /api/assign write path (backlog#124: orch-console
ruling bus #74939). The bus row (agent_messages) and the operator_asks link must commit
in ONE transaction -- the script's own header: "an assignment is not a console-local
note ... no orphan bus row". console_assign.assign() is refactored to call
post_agent_message() on the SAME cursor/transaction as the operator_asks write (not
bus_send.py's send(), which opens its own separate connection and would break that).

These tests pin the existing atomicity/behavior contract against a real ephemeral
Postgres (not mocks -- the whole point is a real transaction boundary), then the
RPC-not-raw-INSERT test is the actual red/green pair for this migration: it fails
against the pre-refactor raw INSERT and passes once assign() calls post_agent_message.
"""
import pathlib
import sys

import psycopg
import pytest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "scripts"))
import console_assign as ca  # noqa: E402

MIGRATIONS_DIR = pathlib.Path(__file__).resolve().parent.parent / "migrations"

_BASE_SCHEMA = """
    CREATE TABLE agents (
        id   TEXT PRIMARY KEY
    );

    CREATE TABLE agent_messages (
        id                 BIGSERIAL PRIMARY KEY,
        from_agent         TEXT NOT NULL,
        to_agent           TEXT NOT NULL,
        message_type       TEXT NOT NULL
            CHECK (message_type IN ('review_request','question','decision','agreed',
                                     'challenge','update','blocker','counter')),
        subject            TEXT NOT NULL,
        body               TEXT NOT NULL,
        priority           TEXT NOT NULL,
        requires_response  BOOLEAN NOT NULL DEFAULT false,
        is_test            BOOLEAN NOT NULL DEFAULT false,
        thread_id          UUID NOT NULL,
        sub_tag            TEXT,
        read_at            TIMESTAMPTZ,
        responded_at       TIMESTAMPTZ,
        created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
    );

    CREATE TABLE operator_asks (
        id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ask            text NOT NULL,
        source_msg_id  bigint,
        thread_id      uuid,
        delegated_to   text,
        created_at     timestamptz NOT NULL DEFAULT now(),
        confirmed_at   timestamptz,
        closed_at      timestamptz,
        closed_reason  text,
        triage_state   text NOT NULL DEFAULT 'captured'
            CHECK (triage_state IN ('captured', 'ask', 'not_an_ask', 'done')),
        triage_summary text,
        triage_evidence_ref text,
        triaged_at     timestamptz,
        triaged_by     text
    );

    CREATE UNIQUE INDEX operator_asks_source_ask_uniq
      ON operator_asks (source_msg_id, ask)
      WHERE source_msg_id IS NOT NULL AND closed_at IS NULL;
"""


