"""fleet_health.sequence_drift() — step 6 of the fleet-health sweep (orch-console
bus #65636/#65639/#65648, hardened per the gate at bus #65719).

WHY: a SERIAL or GENERATED BY DEFAULT AS IDENTITY 'id' column silently accepts an
explicit id in an INSERT without ever advancing its backing sequence. A lane that
hand-writes INSERT ... (id, ...) VALUES (<computed max(id)+1>, ...) — exactly what
happened live (held_commitments id=418, cc-cosem-platform-1; operator_backlog, a
16-id gap) — leaves the sequence behind the table, so the NEXT default-path insert
collides on a duplicate key. sequence_drift() finds every public base table whose
sequence-backed id column's next nextval() would land at or under the table's
current max(id), and setval()s it forward, atomically, one statement per table.

EXECUTED against a real local Postgres — scoped with table_prefix="zz_test_" on
EVERY call (bus #65719 F1): sequence_drift() itself takes this as a safety-scoped
parameter precisely so these tests, run against whatever database DATABASE_URL
happens to point at, can NEVER setval() a real, non-test table even though setval()
is not transactional (a conn.rollback() undoes the CREATE TABLE but NOT a setval()
already applied to a real table's sequence). The repo-root conftest.py's prod-ref
guard already refuses to even START a pytest session against a known production
store; _assert_not_a_production_store() below is a second, local, defense-in-depth
check of the same DSN, independent of that guard's own logic.
"""
import os

import pytest

from conftest import prod_ref
from scripts import fleet_health as fh

DSN = os.environ.get("DATABASE_URL") or os.environ.get("SUPABASE_DB_URL")


def _assert_not_a_production_store():
    ref = prod_ref(DSN)
    assert ref is None, (
        f"DATABASE_URL resolves to the PRODUCTION store '{ref}' — refusing to run "
        f"a sequence_drift() test against it even under table_prefix scoping."
    )


def _by_table(fixed, table):
    return next((f for f in fixed if f[0] == table), None)


@pytest.mark.skipif(not DSN, reason="DATABASE_URL not set (DB-executing test)")
def test_serial_never_called_explicit_id_detected_and_fixed_EXECUTED():
    """A fresh SERIAL whose sequence has never been called (is_called=false) but
    which received an explicit-id insert above its default start — the exact
    held_commitments shape (plain nextval() default)."""
    _assert_not_a_production_store()
    import psycopg
    with psycopg.connect(DSN, autocommit=False) as conn, conn.cursor() as cur:
        try:
            cur.execute("CREATE TABLE zz_test_seq_drift_serial (id serial primary key, name text)")
            cur.execute("INSERT INTO zz_test_seq_drift_serial (id, name) VALUES (5, 'explicit')")
            fixed, errors = fh.sequence_drift(cur, table_prefix="zz_test_")
            assert errors == []
            hit = _by_table(fixed, "zz_test_seq_drift_serial")
            assert hit is not None, "explicit id=5 with an uncalled sequence must be detected"
            assert hit[1] == 1, "pre-fix next nextval() was the untouched default (1)"
            assert hit[2] == 6, "post-fix next nextval() must be max(id)+1 = 6"
            cur.execute("INSERT INTO zz_test_seq_drift_serial (name) VALUES ('via default')")
            cur.execute("SELECT id FROM zz_test_seq_drift_serial WHERE name='via default'")
            assert cur.fetchone()[0] == 6, "the fix must actually prevent the collision"
        finally:
            conn.rollback()


