@pytest.mark.skipif(not DSN, reason="DATABASE_URL not set (DB-executing test)")
def test_idempotent_second_call_is_a_noop_EXECUTED():
    """Calling sequence_drift() twice in a row must only report a fix the FIRST
    time — the second call sees the already-advanced sequence and does nothing."""
    import psycopg
    with psycopg.connect(DSN, autocommit=False) as conn, conn.cursor() as cur:
        try:
            cur.execute("CREATE TABLE zz_test_seq_drift_idempotent (id serial primary key, name text)")
            cur.execute("INSERT INTO zz_test_seq_drift_idempotent (id, name) VALUES (7, 'explicit')")
            first = fh.sequence_drift(cur)
            assert _by_table(first, "zz_test_seq_drift_idempotent") is not None
            second = fh.sequence_drift(cur)
            assert _by_table(second, "zz_test_seq_drift_idempotent") is None, \
                "a just-fixed sequence must not be reported as drifted again"
        finally:
            conn.rollback()
