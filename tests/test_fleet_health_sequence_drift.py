class _PoisonedCursor:
    """Wraps a real cursor; raises on the ONE drift-check statement for
    `poison_table` (identified by that table name appearing, literally, in the
    query text's embedded WITH-CTE — sequence_drift() f-strings the table/seq
    names into that one statement), delegating every other call to the real
    cursor untouched. Used to prove a single table's failure can't take down
    the rest of the sweep (bus #65719 F2) without needing real Postgres
    permission-grant gymnastics to manufacture the error."""

    def __init__(self, real_cur, poison_table):
        self._real = real_cur
        self._poison_table = poison_table
        self._poisoned = False

    def execute(self, query, params=None):
        if (not self._poisoned and self._poison_table in query
                and "WITH m AS" in query):
            self._poisoned = True
            raise RuntimeError("simulated setval failure")
        return self._real.execute(query) if params is None else self._real.execute(query, params)

    def fetchone(self):
        return self._real.fetchone()

    def fetchall(self):
        return self._real.fetchall()


@pytest.mark.skipif(not DSN, reason="DATABASE_URL not set (DB-executing test)")
def test_one_table_error_is_isolated_and_others_still_fixed_EXECUTED():
    """A raise mid-check on ONE table must not kill the sweep for the others —
    isolated behind its own SAVEPOINT, logged as an error, and the surrounding
    transaction must stay usable afterward (bus #65719 F2)."""
    _assert_not_a_production_store()
    import psycopg
    with psycopg.connect(DSN, autocommit=False) as conn, conn.cursor() as real_cur:
        try:
            real_cur.execute("CREATE TABLE zz_test_err_bad (id serial primary key, name text)")
            real_cur.execute("INSERT INTO zz_test_err_bad (id, name) VALUES (3, 'explicit')")
            real_cur.execute("CREATE TABLE zz_test_err_good (id serial primary key, name text)")
            real_cur.execute("INSERT INTO zz_test_err_good (id, name) VALUES (9, 'explicit')")

            poisoned = _PoisonedCursor(real_cur, "zz_test_err_bad")
            fixed, errors = fh.sequence_drift(poisoned, table_prefix="zz_test_err_")

            assert _by_table(errors, "zz_test_err_bad") is not None, \
                "the poisoned table's failure must be reported, not swallowed silently"
            assert _by_table(fixed, "zz_test_err_good") is not None, \
                "the OTHER table must still be checked and fixed despite the first one raising"

            # the surrounding transaction must still be usable (SAVEPOINT isolation worked)
            real_cur.execute("SELECT 1")
            assert real_cur.fetchone()[0] == 1
        finally:
            conn.rollback()
