"""Build B slice 4 (cc-fleet-health spec, bus #73068) -- two independent attended_for()
suppression paths added alongside the existing read/responded/same-thread/hub checks:

ASK-AWARE (incident #59453/ask#1146): an SLA violation whose thread is linked (via
bus_send.py's --link-ask) to an OPEN operator_asks row that has since been re-committed to
a future date, or is flagged waiting_on_operator, is attended from the operator's own side
-- re-paging about it is noise. A thread with no linked ask, or only a CLOSED one, must
behave exactly as before (no regression on the common case).

OFFLINE RECIPIENT (same principle as slice 3's context-gauge veto): a violation addressed
to a recipient with no live (non-offline, recently-heartbeating) agent_status row is
structural noise -- paging about a recipient that does not exist to act on it.

Both new sub-checks must fail toward "not attended" (False) on their own lookup error --
a DB hiccup must never silently swallow a real page, same posture as attended_for's
pre-existing fail-OPEN-toward-paging contract.
"""
import psycopg
import pytest

from scripts import priority_sla_watchdog as s


@pytest.fixture
def sla_attended_db(pg_dsn):
    with psycopg.connect(pg_dsn, autocommit=True) as conn, conn.cursor() as cur:
        cur.execute("DROP SCHEMA public CASCADE")
        cur.execute("CREATE SCHEMA public")
        cur.execute("""
            CREATE TABLE agent_messages (
                id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                from_agent    text NOT NULL,
                to_agent      text NOT NULL,
                thread_id     uuid,
                read_at       timestamptz,
                responded_at  timestamptz,
                created_at    timestamptz NOT NULL DEFAULT now()
            )
        """)
        cur.execute("""
            CREATE TABLE operator_asks (
                id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                thread_id           uuid,
                closed_at           timestamptz,
                waiting_on_operator boolean NOT NULL DEFAULT false,
                outbound_msg_id     bigint,
                committed_date      timestamptz
                                    CHECK (committed_date IS NULL OR outbound_msg_id IS NOT NULL)
            )
        """)
        cur.execute("""
            CREATE TABLE agent_status (
                agent_id        text PRIMARY KEY,
                base_agent_id   text,
                status          text,
                last_heartbeat  timestamptz
            )
        """)
    return pg_dsn


def _insert_message(dsn, *, to_agent="cc-finance", thread_id=None, read_at=None, responded_at=None):
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute(
            "INSERT INTO agent_messages (from_agent, to_agent, thread_id, read_at, responded_at) "
            "VALUES ('orch-console', %s, %s, %s, %s) RETURNING id",
            (to_agent, thread_id, read_at, responded_at))
        mid = cur.fetchone()[0]
        conn.commit()
        return mid


def _insert_ask(dsn, *, thread_id, closed_at=None, waiting_on_operator=False,
                committed_date=None, outbound_msg_id=None):
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute(
            "INSERT INTO operator_asks (thread_id, closed_at, waiting_on_operator, "
            "outbound_msg_id, committed_date) VALUES (%s, %s, %s, %s, %s)",
            (thread_id, closed_at, waiting_on_operator, outbound_msg_id, committed_date))
        conn.commit()


def _insert_live_agent(dsn, agent):
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute(
            "INSERT INTO agent_status (agent_id, base_agent_id, status, last_heartbeat) "
            "VALUES (%s, %s, 'idle', now())",
            (f"{agent}-1", agent))
        conn.commit()


# ── 1. ask re-committed to a future date -> suppress (exact #59453/ask#1146 shape) ──
def test_ask_recommitted_future_suppresses_repage(sla_attended_db):
    mid = _insert_message(sla_attended_db, thread_id="11111111-1111-1111-1111-111111111111")
    _insert_ask(sla_attended_db, thread_id="11111111-1111-1111-1111-111111111111",
                outbound_msg_id=mid, committed_date="2099-01-01")
    _insert_live_agent(sla_attended_db, "cc-finance")

    with psycopg.connect(sla_attended_db) as conn:
        assert s.attended_for(conn, mid, "unresponded", "cc-finance") is True


# ── 2. ask flagged waiting_on_operator -> suppress ───────────────────────────────
def test_ask_waiting_on_operator_suppresses(sla_attended_db):
    mid = _insert_message(sla_attended_db, thread_id="22222222-2222-2222-2222-222222222222")
    _insert_ask(sla_attended_db, thread_id="22222222-2222-2222-2222-222222222222",
                waiting_on_operator=True)
    _insert_live_agent(sla_attended_db, "cc-finance")

    with psycopg.connect(sla_attended_db) as conn:
        assert s.attended_for(conn, mid, "unresponded", "cc-finance") is True


# ── 3. no linked ask at all -> behaves EXACTLY as today (no regression) ─────────
def test_no_linked_ask_behaves_as_today(sla_attended_db):
    mid = _insert_message(sla_attended_db, thread_id="33333333-3333-3333-3333-333333333333")
    _insert_live_agent(sla_attended_db, "cc-finance")

    with psycopg.connect(sla_attended_db) as conn:
        assert s.attended_for(conn, mid, "unresponded", "cc-finance") is False


# ── 4. linked ask exists but is CLOSED -> falls through, never accidentally suppressed ──
def test_closed_linked_ask_falls_through_normal(sla_attended_db):
    mid = _insert_message(sla_attended_db, thread_id="44444444-4444-4444-4444-444444444444")
    _insert_ask(sla_attended_db, thread_id="44444444-4444-4444-4444-444444444444",
                closed_at="2026-01-01", waiting_on_operator=True)
    _insert_live_agent(sla_attended_db, "cc-finance")

    with psycopg.connect(sla_attended_db) as conn:
        assert s.attended_for(conn, mid, "unresponded", "cc-finance") is False


# ── 5. recipient has no live agent_status row at all -> suppress ────────────────
def test_offline_recipient_suppresses(sla_attended_db):
    mid = _insert_message(sla_attended_db, to_agent="cc-retired")

    with psycopg.connect(sla_attended_db) as conn:
        assert s.attended_for(conn, mid, "unresponded", "cc-retired") is True


# ── 6. live recipient -> unaffected by the offline check (normal ladder decides) ──
def test_live_recipient_not_affected_by_offline_check(sla_attended_db):
    mid = _insert_message(sla_attended_db, to_agent="cc-finance")
    _insert_live_agent(sla_attended_db, "cc-finance")

    with psycopg.connect(sla_attended_db) as conn:
        assert s.attended_for(conn, mid, "unresponded", "cc-finance") is False


# ── 7. both new lookups failing -> fails OPEN (does NOT suppress) ───────────────
def test_both_new_lookups_failing_fails_open_not_suppressed(sla_attended_db):
    mid = _insert_message(sla_attended_db, to_agent="cc-finance",
                          thread_id="55555555-5555-5555-5555-555555555555")
    with psycopg.connect(sla_attended_db) as conn, conn.cursor() as cur:
        cur.execute("DROP TABLE operator_asks")
        cur.execute("DROP TABLE agent_status")
        conn.commit()

    with psycopg.connect(sla_attended_db) as conn:
        assert s.attended_for(conn, mid, "unresponded", "cc-finance") is False
