BEGIN;

CREATE TABLE IF NOT EXISTS public.provisioner_access_log (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  verb           text NOT NULL CHECK (verb IN ('provision', 'revert')),
  client_key     text NOT NULL,
  silo_ref       text NOT NULL,
  bundle_sha256  text NOT NULL,
  gate_id        text NOT NULL,
  peer_uid       text,
  reason         text NOT NULL DEFAULT '',
  status         text NOT NULL CHECK (status IN ('started', 'ok', 'error')),
  error_code     text,
  ts_start       timestamptz NOT NULL DEFAULT now(),
  ts_end         timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now()
);

-- one 'ok' per (gate_id, verb), forever — see header
CREATE UNIQUE INDEX IF NOT EXISTS provisioner_access_log_gate_spent
  ON public.provisioner_access_log (gate_id, verb) WHERE status = 'ok';

CREATE INDEX IF NOT EXISTS provisioner_access_log_stuck_idx
  ON public.provisioner_access_log (ts_start) WHERE status = 'started';

DO $$ BEGIN
  CREATE ROLE provisioner_log_role NOLOGIN;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

REVOKE ALL ON public.provisioner_access_log FROM PUBLIC, authenticated, anon, service_role;
REVOKE ALL ON SEQUENCE public.provisioner_access_log_id_seq FROM PUBLIC, authenticated, anon, service_role;
GRANT INSERT, UPDATE, SELECT ON public.provisioner_access_log TO provisioner_log_role;
GRANT USAGE, SELECT ON SEQUENCE public.provisioner_access_log_id_seq TO provisioner_log_role;
-- No DELETE grant to anyone, including provisioner_log_role -- append-only by omission.

COMMIT;
