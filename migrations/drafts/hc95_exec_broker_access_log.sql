--
-- SUPABASE DEFAULT-PRIVILEGES NOTE (bus #72301, same root cause as the
-- collision above -- a table that looked locked down was actually wide
-- open): on Supabase, authenticated/anon/service_role get their default
-- grants DIRECTLY, not via PUBLIC -- `REVOKE ALL ... FROM PUBLIC` alone does
-- NOT touch them, so a table believed deny-all can still be reachable
-- through the API surface those roles serve. Every REVOKE below names all
-- four explicitly; orch-console confirmed this is exactly what the LIVE
-- apply needed and this draft now matches it.
--
-- Append-only from every vantage but the broker's own DB role: no DELETE grant to
-- anyone, ever; UPDATE is only how the broker finalizes its OWN just-inserted row
-- (started -> ok/error, see scripts/lib/exec_broker/vault_log.py), never a
-- general-purpose update path. A row stuck at status=started past a threshold is
-- itself a P1 (broker crashed mid-call) per bus #56697's daily reconcile + dead-man
-- heartbeat -- that job is OUT of scope for this migration/milestone (a).
--
-- KNOWN LIMITATION (orch-console gate review, PR#434/bus #70919, required
-- before real-ref use, not blocking milestone (a) on QA): the GRANT below is
-- table-wide INSERT+UPDATE, so "the broker finalizes only its own
-- just-inserted row" is enforced by vault_log.py's own code TODAY, not by the
-- grant/schema -- exec_broker_role could technically UPDATE an arbitrary
-- historical row (flip error->ok, rewrite sql_sha256) if the application code
-- had a bug or were compromised. For an audit-integrity table, that must be
-- enforced by the DB itself (e.g. a BEFORE UPDATE trigger that only allows a
-- transition FROM status='started' on a row whose exec_ledger_id/ts_start the
-- update isn't changing, or column-level grants + a narrower updatable view).
-- Defer the actual trigger/grant hardening to rollout step (c) (same gate as
-- option (2)'s full migration/PR re-check) -- tracked here, not silently
-- dropped.
--
-- exec_broker_role needs its own LOGIN password, minted by orch-console at apply
-- time (ALTER ROLE exec_broker_role LOGIN PASSWORD '...') -- never committed here.
-- This is a SEPARATE credential from the general fleet-bus DATABASE_URL: the
-- broker's single DB connection authenticates as this role, which can read
-- agent_messages (to re-check a gate_id) and write ONLY exec_broker_access_log --
-- it must not be handed the same role the rest of the fleet uses to write
-- agent_messages/operator_log/etc. (open provisioning item for orch-console).

CREATE TABLE IF NOT EXISTS exec_broker_access_log (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exec_ledger_id text NOT NULL,
  caller         text NOT NULL,
  project_ref    text NOT NULL,
  sql_sha256     text NOT NULL,
  reason         text NOT NULL DEFAULT '',
  gate_id        text,
  status         text NOT NULL CHECK (status IN ('started', 'ok', 'error')),
  error_code     text,
  ts_start       timestamptz NOT NULL DEFAULT now(),
  ts_end         timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now()
);

DO $$ BEGIN
  CREATE ROLE exec_broker_role NOLOGIN;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

REVOKE ALL ON exec_broker_access_log FROM PUBLIC, authenticated, anon, service_role;
REVOKE ALL ON SEQUENCE exec_broker_access_log_id_seq FROM PUBLIC, authenticated, anon, service_role;
GRANT INSERT, UPDATE, SELECT ON exec_broker_access_log TO exec_broker_role;
GRANT USAGE, SELECT ON SEQUENCE exec_broker_access_log_id_seq TO exec_broker_role;
-- No DELETE grant to anyone, including exec_broker_role -- append-only by omission.

