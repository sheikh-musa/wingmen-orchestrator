"""node_modules_content_dedup.py — content-based hardlink dedup across worktree node_modules
trees (cc-fleet-health §4.6, op#31841-era disk-CRIT priority elevation, orch-console #71581).

WHY THIS SHAPE, NOT A PACKAGE-MANAGER MIGRATION: the backlog item was framed as "pnpm store
dedup", but the actual GOAL is reclaiming the ~9GB of byte-identical duplicate files across many
worktrees of the same repo (cosem-adcda, cosem-platform, ...) on different branches. Switching a
live, actively-developed, government-client-adjacent codebase's package manager (npm -> pnpm)
changes install/build semantics across every worktree at once -- exactly the kind of broad,
hard-to-fully-review change CLAUDE.md §2 says to be conservative about. Hardlinking achieves the
SAME disk savings with a categorically smaller risk surface: a hardlink only changes which inode
a directory ENTRY points to; it never touches file CONTENT, and POSIX guarantees any process that
already has the old file open-for-read keeps reading exactly what it had, unaffected (unlike `rm`,
which is irreversible without a fresh install -- see cc-fleet-health memory
lsof-emptiness-alone-insufficient-for-worktree-nodemodules-safety.md, today's near-miss on exactly
that distinction). No install/build step, lockfile, or resolved dependency tree changes at all.

SAFETY MODEL (CLAUDE.md §2 — provably safe, reversible, dead-man's-switch):
  1. Byte-identical ONLY: two files are candidates only if (size, sha256) match exactly.
  2. Re-verify immediately before each link: a file could change between the scan and the apply
     (a fresh install landing mid-run) -- re-read and re-compare content right before linking,
     never trust a precomputed group blindly. A mismatch aborts THAT pair only (fail-loud, logged,
     independent of every other pair).
  3. Recency gate: skip any file modified within `min_age_s` (default 10 min) -- a file that
     young could still be mid-write from an in-progress install; wait for it to settle.
  4. Coarse global gate: if ANY npm/pnpm/yarn install process is running anywhere on the system,
     the whole sweep skips (reported, not silent) rather than risk racing a live install.
  5. Symlinks are never touched (scan excludes them outright).
  6. Reversible in the strict sense that matters: if this ever linked something it shouldn't
     have, a fresh `npm install` in the affected worktree restores an independent copy (same as
     recovering from the `rm`-based near-miss) -- the content was NEVER wrong, only the on-disk
     sharing of otherwise-identical bytes.
  7. Fail-loud: a per-pair error is recorded, never swallowed; one failure never aborts the sweep.
     --apply does nothing by default; detect-only is the default mode.

Usage (from ~/wingmen/orchestrator):
  .venv/bin/python3 -m scripts.node_modules_content_dedup                # DETECT-ONLY
  .venv/bin/python3 -m scripts.node_modules_content_dedup --apply        # link for real
  .venv/bin/python3 -m scripts.node_modules_content_dedup --json
Roots scanned are the colon-separated glob patterns in NM_DEDUP_FAMILIES (env), default the known
duplicate-heavy families; see the launchd plist for the armed list.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import pathlib
import subprocess
import sys
import time

GB = 1 << 30
MB = 1 << 20

FAMILIES = [p for p in os.environ.get(
    "NM_DEDUP_FAMILIES",
    "~/wingmen/projects/cosem-adcda*:~/wingmen/projects/cosem-platform*:~/wingmen/projects/cosem-tdu*",
).split(":") if p]
MIN_AGE_S = float(os.environ.get("NM_DEDUP_MIN_AGE_S", str(10 * 60)))
# Skip hashing files below this size: a node_modules tree commonly has 100k+s of tiny files
# (.d.ts stubs, licenses, small JSON) whose AGGREGATE dedup savings are negligible next to the
# I/O cost of hashing every one. 4KB keeps the big wins (bundled JS/binaries/wasm) while cutting
# the scan from ~600k files to a small fraction of that on this fleet's worktrees.
MIN_FILE_SIZE = int(os.environ.get("NM_DEDUP_MIN_FILE_SIZE", str(4096)))
HASH_CHUNK = 1 << 20
INSTALL_MARKERS = ("npm install", "npm ci", "pnpm install", "pnpm i ", "yarn install", "yarn add")


def log(msg: str) -> None:
    print(msg, flush=True)


# ---- pure-ish content identity -------------------------------------------------
def _sha256(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            chunk = f.read(HASH_CHUNK)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def content_key(path: pathlib.Path):
    """(size, sha256) -- size first so two differently-sized files are NEVER equal without
    even hashing the larger one (cheap short-circuit the test suite pins)."""
    size = path.stat().st_size
    return (size, _sha256(path))


# ---- scanning -------------------------------------------------------------------
def scan_node_modules_files(roots, *, min_size: int = 0):
    """Yield every regular (non-symlink) file under any `node_modules` dir within `roots` that
    is at least `min_size` bytes (0 = no filter; the CLI defaults to MIN_FILE_SIZE)."""
    for root in roots:
        root = pathlib.Path(root)
        if not root.is_dir():
            continue
        for dirpath, dirnames, filenames in os.walk(root):
            dp = pathlib.Path(dirpath)
            if "node_modules" not in dp.parts:
                continue
            for fn in filenames:
                p = dp / fn
                try:
                    if p.is_symlink():
                        continue
                    st = p.stat()
                    if st.st_size < min_size:
                        continue
                except OSError:
                    continue
                yield p


def group_by_content(files, min_group_size: int = 2):
    """Group files by (size, sha256). Groups below `min_group_size` are dropped -- a lone file
    has nothing to dedup against. FAIL-SAFE: a file that can't be hashed (removed mid-scan,
    permission error) is silently excluded from grouping (never raises the whole sweep)."""
    by_key: dict = {}
    for p in files:
        try:
            key = content_key(p)
        except OSError:
            continue
        by_key.setdefault(key, []).append(p)
    return {k: v for k, v in by_key.items() if len(v) >= min_group_size}


# ---- the hardlinking core (fully unit-tested, fs side effects only) -----------
def dedup_group(paths, *, dry_run: bool, min_age_s: float = MIN_AGE_S):
    """Within one content-identical group, hardlink every path to the FIRST (canonical) one.
    Re-verifies content immediately before each link (defense in depth against a race between
    the scan and this call) and skips anything modified more recently than `min_age_s`."""
    rep = {"linked": 0, "would_link": 0, "already_linked": 0,
           "skipped_too_recent": 0, "errors": []}
    if not paths:
        return rep
    canonical = paths[0]
    try:
        canon_stat = canonical.stat()
    except OSError as e:
        rep["errors"].append(f"canonical unreadable {canonical}: {e}")
        return rep
    now = time.time()
    for p in paths[1:]:
        try:
            st = p.stat()
        except OSError as e:
            rep["errors"].append(f"stat failed {p}: {e}")
            continue
        if st.st_ino == canon_stat.st_ino and st.st_dev == canon_stat.st_dev:
            rep["already_linked"] += 1
            continue
        if (now - st.st_mtime) < min_age_s or (now - canon_stat.st_mtime) < min_age_s:
            rep["skipped_too_recent"] += 1
            continue
        if dry_run:
            rep["would_link"] += 1
            continue
        # RE-VERIFY immediately before touching anything -- never trust the precomputed group.
        try:
            if _sha256(p) != _sha256(canonical) or p.stat().st_size != canonical.stat().st_size:
                rep["errors"].append(f"content changed since scan, mismatch (spared): {p}")
                continue
        except OSError as e:
            rep["errors"].append(f"re-verify failed {p}: {e}")
            continue
        tmp = p.with_name(p.name + ".dedup-tmp")
        try:
            if tmp.exists():
                tmp.unlink()
            os.link(canonical, tmp)
            os.replace(tmp, p)  # atomic swap; p's old inode is simply unreferenced here, not
                                 # truncated -- any process with it already open keeps reading it
            rep["linked"] += 1
        except OSError as e:
            rep["errors"].append(f"link failed {p}: {e}")
            try:
                if tmp.exists():
                    tmp.unlink()
            except OSError:
                pass
    return rep


# ---- coarse global safety gate -------------------------------------------------
def _ps_snapshot() -> str:
    try:
        r = subprocess.run(["ps", "-axo", "command"], capture_output=True, text=True, timeout=10)
        return r.stdout
    except (subprocess.TimeoutExpired, OSError):
        return ""


def any_install_running() -> bool:
    """FAIL-SAFE: if `ps` itself errors, _ps_snapshot returns "" and this returns False -- that
    is an accepted gap (a hung ps is its own loud failure elsewhere), not a reason to silently
    refuse every sweep forever."""
    snap = _ps_snapshot().lower()
    return any(marker in snap for marker in INSTALL_MARKERS)


# ---- family expansion (mirrors worktree_nodemodules_reaper's pattern) --------
def find_family_roots(patterns, *, home=None):
    home = pathlib.Path(home) if home else pathlib.Path.home()
    seen, out = set(), []
    for pat in patterns:
        pat = pat.replace("~", str(home), 1) if pat.startswith("~") else pat
        base = pathlib.Path(pat)
        try:
            matches = sorted(base.parent.glob(base.name))
        except OSError:
            continue
        for d in matches:
            if not d.is_dir():
                continue
            try:
                rp = d.resolve()
            except OSError:
                rp = d
            if rp not in seen:
                seen.add(rp)
                out.append(d)
    return out


# ---- sweep ----------------------------------------------------------------------
def sweep(roots, *, dry_run: bool, min_age_s: float = MIN_AGE_S, min_size: int = MIN_FILE_SIZE):
    if any_install_running():
        return {"skipped_install_in_progress": True, "would_free_bytes": 0,
                "freed_bytes": 0, "errors": [], "groups": 0}
    files = list(scan_node_modules_files(roots, min_size=min_size))
    groups = group_by_content(files)
    total_would_free = 0
    total_freed = 0
    all_errors = []
    for paths in groups.values():
        size = paths[0].stat().st_size if paths else 0
        rep = dedup_group(paths, dry_run=dry_run, min_age_s=min_age_s)
        total_would_free += rep["would_link"] * size
        total_freed += rep["linked"] * size
        all_errors.extend(rep["errors"])
    return {"skipped_install_in_progress": False, "would_free_bytes": total_would_free,
            "freed_bytes": total_freed, "errors": all_errors, "groups": len(groups)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--apply", action="store_true", help="link for real (default: detect-only)")
    ap.add_argument("--json", action="store_true", help="machine-readable report")
    args = ap.parse_args(argv)
    dry_run = not args.apply

    roots = find_family_roots(FAMILIES)
    summary = sweep(roots, dry_run=dry_run)
    summary["roots_scanned"] = len(roots)

    if args.json:
        log(json.dumps(summary, indent=2))
    else:
        if summary["skipped_install_in_progress"]:
            log("[nm-dedup] SKIPPED — an npm/pnpm/yarn install is running right now")
        else:
            mode = "APPLY" if args.apply else "DETECT-ONLY"
            tag = "freed" if args.apply else "would_free"
            bytes_n = summary["freed_bytes"] if args.apply else summary["would_free_bytes"]
            log(f"[nm-dedup {mode}] roots={summary['roots_scanned']} groups={summary['groups']} "
                f"{tag}~{bytes_n // MB}MB ({bytes_n / GB:.2f}GB) errors={len(summary['errors'])}")
            for e in summary["errors"]:
                log(f"  ! {e}")

    if args.apply and summary["errors"]:
        return 1
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
