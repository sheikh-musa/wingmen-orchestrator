#!/usr/bin/env python3
"""fleet_health.py — standing fleet-health sweep (cheap, ~0 model tokens).

The orchestrator used to notice dead lanes only when the operator did. This
runs on a launchd timer so the substrate self-heals:

  1. STALE -> offline: any agent whose heartbeat is older than STALE_MIN is
     marked offline (the Fleet Console then shows reality, not a phantom).
  2. REAP: offline rows older than PRUNE_DAYS are deleted (no 50-day zombies).
  3. RECONCILE: cross-check agent_status against live tmux sessions and flag
     drift — a "working" row with no live session (crashed lane) or a live
     CC session with no fresh row (unregistered lane).
  4. ARCHIVE dead-letters: mark read the unread agent_messages addressed to
     agents that are gone (no fresh heartbeat AND no sent-message in 24h) and
     older than ARCHIVE_MIN_AGE_H. Keeps the console's bus/queue counts honest
     (dead lanes accumulate tombstones nobody drains — operator-flagged 2026-07-16)
     WITHOUT hiding anything live: recipients that heartbeat OR have sent recently
     (incl. unregistered coordinators like cc-orchestrator/orch-console) are
     spared, human-addressed (musa/operator) + substrate rows are never touched,
     and only messages older than the grace window are swept.
  6. SEQUENCE SELF-HEAL (orch-console bus #65636/#65639/#65648, hardened per
     bus #65719 gate): a SERIAL or GENERATED BY DEFAULT AS IDENTITY column
     silently accepts an explicit id in an INSERT without ever advancing its
     backing sequence — both shapes exist on the substrate (held_commitments is
     SERIAL, operator_backlog is IDENTITY BY DEFAULT). A lane hand-writing
     INSERT ... (id, ...) VALUES (<computed-number>, ...) — e.g. max(id)+1 —
     leaves the sequence behind; the NEXT default-path insert then collides on
     a duplicate key (hit live: held_commitments id=418, bus #65636). For every
     public base table with an 'id' column backed by a sequence (found via
     pg_get_serial_sequence — covers both SERIAL and IDENTITY uniformly), if
     the sequence's next nextval() would land at or under the table's current
     max(id), setval() it forward — atomically in one statement per table via
     GREATEST(max_id, last_value), which can never move a sequence backward
     (bus #65719 F3). Idempotent, cheap (one round trip per table), never
     touches a table whose sequence is already ahead (a gap from a rolled-back
     insert is healthy, not drift, and is left alone). Each table's check/fix
     is isolated behind its own SAVEPOINT (bus #65719 F2): one bad table never
     aborts the sweep. sequence_drift() takes an optional table_prefix so
     tests can scope themselves to synthetic tables only (bus #65719 F1) —
     production calls (here) pass none, scanning every public base table.

Only touches agent_status (status + delete), agent_messages.read_at (archive),
and any drifted sequence's last_value (setval). Run on demand:
    python3 scripts/fleet_health.py [--quiet] [--no-archive]
"""
