def live_tmux_sessions():
    try:
        out = subprocess.run(["tmux", "ls"], capture_output=True, text=True, timeout=10).stdout
    except Exception:
        return set()
    return {ln.split(":", 1)[0] for ln in out.splitlines() if ":" in ln}


def observed_activity(recent_bus, tmux_session, live_sessions):
    """OBSERVED-ACTIVITY gate before offline-marking (cc-fleet-health, re-derived from #23952,
    Nazim #24044). A stale HEARTBEAT is not death: an on-demand body (boot_quality.sh has no
    heartbeat loop by design, CAI-729→733) goes stale while working. Before flipping such an
    agent offline, look for OBSERVED activity that proves the identity is alive despite the
    stale column:
      * recent_bus  — it posted a bus row (agent_messages.from_agent) within the staleness
                      window (resolved in SQL against the SAME now() the reaper uses); host-
                      independent and unambiguous.
      * live tmux   — its registered tmux_session is live ON THIS HOST (a co-located pane is up).
    Any observed => (True, reason) -> caller SKIPS the flip. Neither => (False, ...) -> the
    agent is dead as far as we can observe, flip as before. This is 'observation > the heartbeat
    column' (same principle as the pane_busy collapse), NOT a skip-list: a genuinely dead body
    (no hb AND no observed activity) still flips, so this cannot hide a real death — unlike
    adding it to protected_agents, which would (Nazim #24044). cc_session_costs is intentionally
    NOT used: it keys on cc_identity/sub_tag and shared-identity workers mis-map (handoff caveat)."""
    if recent_bus:
        return True, "recent bus row within staleness window"
    if tmux_session and tmux_session in live_sessions:
        return True, f"live tmux session '{tmux_session}' on this host"
    return False, "no observed activity (no recent bus row, no live co-located session)"


def _undeliverable(to_agent) -> bool:
    """A to_agent with NO possible live wake owner — one that can NEVER be woken: the operator
    handle 'musa', the non-address 'substrate', any id that is not a cc-* worker / cai / a
    console. Uses agent_wake's SSOT eligibility on the most-permissive floor (P0 +
    requires_response) so the hub (cc-orchestrator, narrow-floor-eligible) is NEVER misread as
    a dead-letter sink. Distinct from a gone-but-once-live cc lane, which is eligible-by-
    identity and is step 4's job. Imported lazily so importing this module stays
    load_dotenv-free under pytest."""
    if not to_agent:
        return False
    from nervous_system.agent_wake import is_wake_eligible_recipient
    return not is_wake_eligible_recipient(to_agent, "P0", True)


# EXEMPT — cursor-relay-consumed rows are NOT dead-letters. The operator ('musa') ⚠️ weekly-pace
# rows are CONSUMED by nervous_system/weekly_alert_relay.py — a durable-CURSOR launchd daemon that
# pushes each to the operator's phone (nazim pen). A cursor relay NEVER sets read_at, so these stay
# unread forever despite being DELIVERED, and are invisible to the agent_wake/read_at test
# _undeliverable() uses — so without this they FALSE-flag as dead-letters (2026-09-10: that cascaded
# into a "retarget the producer" advisory, but that retarget was already tried in b72a6fe and
# REVERTED by Nazim 37739; test_weekly_limit_operator_target.py pins OPERATOR_AGENT='musa' to the
# relay, and weekly_limit_monitor.py:~521 documents "this is NOT a dead-letter"). Canonical watched
# set = weekly_alert_relay._WHERE; this mirrors it. Excluding these from the COUNT still lets a
# genuine 'musa' misroute (a non-⚠️ / non-SRE row) surface.
_RELAY_CONSUMED_SQL = ("to_agent = 'musa' AND from_agent = 'cc-fleet-health' "
                       "AND coalesce(subject,'') LIKE '⚠️%'")  # coalesce: NULL-subject must NOT be
# exempt (a NULL LIKE is NULL -> NOT(NULL)=NULL drops the row = fail-open hide; Nazim PR#101 gate).


def _relay_consumed(to_agent, from_agent, subject) -> bool:
    """PURE twin of _RELAY_CONSUMED_SQL (drift-guarded by test): True iff this row is a
    weekly_alert_relay cursor-consumed operator ⚠️ row — delivered to the operator's phone, NOT a
    dead-letter. Keep in lockstep with _RELAY_CONSUMED_SQL and weekly_alert_relay._WHERE."""
    return (to_agent == "musa" and from_agent == "cc-fleet-health"
            and (subject or "").startswith("⚠️"))


def surface_dead_letters(cur, dry=False):
    """Detect unread rows whose to_agent is structurally undeliverable and SURFACE them to
    orch-console — ONE coalesced row per (to_agent) per day (deduped on today's own surface
    rows), NEVER reaped. Reaping would hide a real misroute; step 4 already spares these.
    Cursor-relay-consumed rows (see _RELAY_CONSUMED_SQL) are excluded — they are delivered, not
    dead. Returns the to_agents surfaced (or that WOULD be, when dry)."""
    cur.execute(f"""SELECT to_agent, count(*) AS n, min(created_at) AS oldest,
                          max(created_at) AS newest,
                          count(*) FILTER (WHERE priority IN ('P0','P1')) AS hi
                   FROM agent_messages
                   WHERE read_at IS NULL AND to_agent IS NOT NULL
                     AND NOT ({_RELAY_CONSUMED_SQL})
                   GROUP BY to_agent""")
    surfaced = []
    for to_agent, n, oldest, newest, hi in cur.fetchall():
        if not _undeliverable(to_agent):
            continue
        # A human-opened liaison address (cto-desktop) is surfaced at most once per WEEK — its
        # rows are read when the human next opens that session, so a daily page is noise. A real
        # undeliverable address (a misroute / retired agent) stays once-per-DAY until fixed.
        human = _human_opened(to_agent)
        period = "week" if human else "day"
        cur.execute(f"""SELECT 1 FROM agent_messages
                       WHERE from_agent='cc-fleet-health' AND to_agent='orch-console'
                         AND subject LIKE %s
                         AND created_at >= date_trunc('{period}', now()) LIMIT 1""",
                    (f"dead-letter[{to_agent}]:%",))
        if cur.fetchone():
            continue
        if not dry:
            if human:
                subj = f"dead-letter[{to_agent}]: {n} unread for a human-opened liaison session (weekly count)"
                body = (f"{n} unread agent_messages are addressed to '{to_agent}', a HUMAN-OPENED "
                        f"liaison session (not an agent). They are read when the human next opens it "
                        f"— superseded, not lost (oldest {oldest}, newest {newest}, P0/P1={hi}). NOT "
                        f"reaped and NOT paged daily; this is a weekly one-line count so they don't "
                        f"rot unseen. If the address is retired, remove it from _HUMAN_OPENED.")
            else:
                subj = f"dead-letter[{to_agent}]: {n} unread with no live wake owner"
                body = (f"{n} unread agent_messages are addressed to '{to_agent}', which has NO live "
                        f"wake owner — agent_wake will never deliver there, so they accrue silently "
                        f"(oldest {oldest}, newest {newest}, P0/P1={hi}). NOT reaped: a misroute must "
                        f"be fixed (retarget the producer) or the address retired, not hidden. "
                        f"Surfaced once/day by the cc-fleet-health dead-letter detector.")
            cur.execute("SELECT set_config('app.current_agent_id','cc-fleet-health',true)")
            # RPC on the EXISTING cursor (backlog#124, bus #74939), not bus_send.send() --
            # this loop can post multiple to_agents before the ONE conn.commit() in main()
            # after this function returns; send()'s own connection would break that batch.
            cur.execute(
                "SELECT * FROM post_agent_message('cc-fleet-health','orch-console','update',"
                "%s,%s,'P2',false,%s,%s,%s,%s)",
                (subj, body, str(uuid.uuid4()), None, False, None))
        surfaced.append(to_agent)
    return surfaced


def sequence_drift(cur, table_prefix=None):
    """Find every public base table's sequence-backed 'id' column (SERIAL or
    GENERATED BY DEFAULT AS IDENTITY — pg_get_serial_sequence covers both) whose
    next nextval() would land at or under the table's current max(id), and
    setval() it forward — atomically, in ONE statement per table (bus #65719
    F3: GREATEST(max_id, last_value) can never move a sequence backward; doing
    the max(id) read and the setval() in the same round trip closes the TOCTOU
    window a separate read-then-write pair would leave open to a concurrent
    nextval()).

    table_prefix: restrict the scan to tables whose name starts with this
    prefix (bus #65719 F1 — tests pass e.g. "zz_test_" so a shared test
    database's real tables are never touched; the production default, None,
    scans every public base table).

    Returns (fixed, errors):
      fixed  — [(table, old_next, new_next), ...] for tables actually fixed.
      errors — [(table, str(exc)), ...] for tables whose check/fix raised; each
                is isolated behind its own SAVEPOINT (bus #65719 F2) so one bad
                table (permission error, a sequence dropped out from under its
                column) never aborts the whole sweep or the caller's txn."""
    query = """SELECT c.table_name
               FROM information_schema.columns c
               JOIN information_schema.tables t
                 ON t.table_schema = c.table_schema AND t.table_name = c.table_name
               WHERE c.table_schema = 'public' AND c.column_name = 'id'
                 AND t.table_type = 'BASE TABLE'"""
    params = ()
    if table_prefix:
        query += " AND c.table_name LIKE %s"
        params = (table_prefix + "%",)
    query += " ORDER BY c.table_name"
    cur.execute(query, params)
    tables = [r[0] for r in cur.fetchall()]

    fixed, errors = [], []
    for table in tables:
        cur.execute("SAVEPOINT seq_drift_tbl")
        try:
            cur.execute("SELECT pg_get_serial_sequence(%s, 'id')", (table,))
            seq = cur.fetchone()[0]
            if not seq:
                cur.execute("RELEASE SAVEPOINT seq_drift_tbl")
                continue  # plain integer id, no backing sequence — nothing to drift
            cur.execute(f"""
                WITH m AS (SELECT coalesce(max(id), 0) AS max_id FROM "{table}"),
                     s AS (SELECT last_value, is_called FROM {seq})
                SELECT m.max_id, s.last_value,
                       CASE WHEN s.is_called THEN s.last_value + 1 ELSE s.last_value END AS next_val,
                       CASE WHEN (CASE WHEN s.is_called THEN s.last_value + 1 ELSE s.last_value END) <= m.max_id
                            THEN (SELECT setval('{seq}', GREATEST(m.max_id, s.last_value), true))
                            ELSE NULL END AS fixed_to
                FROM m, s""")
            max_id, last_value, next_val, fixed_to = cur.fetchone()
            cur.execute("RELEASE SAVEPOINT seq_drift_tbl")
            if fixed_to is not None:
                fixed.append((table, next_val, fixed_to + 1))
        except Exception as exc:
            cur.execute("ROLLBACK TO SAVEPOINT seq_drift_tbl")
            cur.execute("RELEASE SAVEPOINT seq_drift_tbl")
            errors.append((table, str(exc)))
    return fixed, errors


# 7. ASKS-JOB EXIT WATCH (console #78250): asks_reconcile_daily exited 1 for days (#2141
# refused every run) and nobody read its log. Any asks launchd job, plus the commitment
# sweeper (it carries hc#581's ask deadlines), whose LAST exit is non-zero pages orch-console
# ONCE per failure episode; the entry clears when the job exits 0 again.
EXIT_WATCH_LABEL_RE = re.compile(r"^dev\.wingmen\.(asks-.+|commitment-sweeper)$")
EXIT_WATCH_STATE = _ORCH_DIR / "logs" / "asks_job_exit_watch.json"


def parse_launchctl_list(text):
    """`launchctl list` -> {label: last_exit_status:int} for watched labels."""
    out = {}
    for line in text.splitlines():
        parts = line.split("\t")
        if len(parts) != 3 or not EXIT_WATCH_LABEL_RE.match(parts[2]):
            continue
        try:
            out[parts[2]] = int(parts[1])
        except ValueError:
            continue
    return out


def exit_watch_plan(statuses, state):
    """PURE: (labels to page now, new state). state maps label -> exit status already
    paged. Page when non-zero and not yet paged for this status; clear on exit 0."""
    to_page, new = [], dict(state)
    for label, status in sorted(statuses.items()):
        if status == 0:
            new.pop(label, None)
        elif state.get(label) != status:
            to_page.append((label, status))
    return to_page, new


def asks_job_exit_watch(dry=False):
    """Impure. Returns labels paged. A failure here is printed loud and never fatal."""
    import json
    try:
        text = subprocess.run(["launchctl", "list"], capture_output=True, text=True,
                              timeout=20, check=True).stdout
        state = json.loads(EXIT_WATCH_STATE.read_text()) if EXIT_WATCH_STATE.exists() else {}
    except Exception as e:  # noqa: BLE001
        print(f"ASKS-JOB EXIT WATCH could not read launchd/state: {type(e).__name__}: {e}")
        return []
    to_page, new = exit_watch_plan(parse_launchctl_list(text), state)
    paged = []
    for label, status in to_page:
        if dry:
            print(f"[dry] ASKS-JOB EXIT WATCH would page: {label} last exit {status}")
            continue
        try:
            from scripts import bus_send
            log = _ORCH_DIR / "logs" / f"{label.split('.')[-1]}.log"
            bus_send.send("cc-fleet-health", "orch-console", "blocker",
                          f"asks job {label} exited {status}",
                          f"TL;DR: launchd job {label} last exited with status {status}, so "
                          f"its run failed or only half-ran.\n\n- Log: {log}\n- This is "
                          "paged once per failure; it clears when the job next exits 0.",
                          "P1", req=True)
            new[label] = status
            paged.append(label)
        except (Exception, SystemExit) as e:  # noqa: BLE001 — unstamped, retried next sweep
            print(f"ASKS-JOB EXIT WATCH page FAILED for {label}: {type(e).__name__}: {e}")
    if not dry:
        try:
            EXIT_WATCH_STATE.write_text(json.dumps(new))
        except Exception as e:  # noqa: BLE001
            print(f"ASKS-JOB EXIT WATCH state write FAILED: {type(e).__name__}: {e}")
    return paged


# 8. IDLE-IN-TRANSACTION WATCH (console #78501/#78690/#78695, step A = MEASURE mode).
# pid 490867 sat idle in transaction ~2d21h holding a lock on agent_messages: a hand-rolled
# bus-watch loop inside a lane's session that never committed (scripts/bus_watch.py is now
# the sanctioned loop). Every session idle in tx past 5 min goes to a measure log, so the
# 7-day soak can show what an idle_in_transaction_session_timeout would break; past 30 min
# it WARNs in the sweep output; past 1 h it pages orch-console P2 ONCE per episode
# (pid + xact_start, so a reused pid is a new episode). It NEVER terminates anything:
# terminating a backend stays console's call.
IDLE_TX_MEASURE_S, IDLE_TX_WARN_S, IDLE_TX_PAGE_S = 300, 1800, 3600
IDLE_TX_QUERY_CHARS = 120
IDLE_TX_STATE = _ORCH_DIR / "logs" / "idle_in_tx_watch.json"
IDLE_TX_MEASURE_LOG = _ORCH_DIR / "logs" / "idle_in_tx_measure.jsonl"
_SQL_LITERAL_RE = re.compile(r"'(?:[^']|'')*'")


def mask_query(query, n=IDLE_TX_QUERY_CHARS):
    """Query prefix with every string literal masked to '?' (a literal can carry a secret,
    e.g. ALTER ROLE ... PASSWORD '...'), whitespace collapsed, bounded to n chars."""
    q = _SQL_LITERAL_RE.sub("'?'", query or "")
    return " ".join(q.split())[:n]


def idle_tx_key(s):
    return f"{s['pid']}:{int(s['xact_epoch'])}"


def idle_tx_plan(sessions, state, *, measure_s=IDLE_TX_MEASURE_S, warn_s=IDLE_TX_WARN_S,
                 page_s=IDLE_TX_PAGE_S):
    """PURE: classify idle-in-tx sessions. Returns measure (>= measure_s), warn (>= warn_s,
    below page_s), page (>= page_s, not yet paged this episode) and the new state, which
    keeps only episodes still idle past page_s so an ended episode drops out."""
    measure, warn, page, new = [], [], [], {}
    for s in sessions:
        idle = s["idle_s"]
        if idle < measure_s:
            continue
        measure.append(s)
        if idle < warn_s:
            continue
        if idle < page_s:
            warn.append(s)
            continue
        key = idle_tx_key(s)
        if state.get(key) == "paged":
            new[key] = "paged"
        else:
            page.append(s)
    return {"measure": measure, "warn": warn, "page": page, "state": new}


def idle_tx_page_body(s):
    return (f"TL;DR: backend pid {s['pid']} has been idle in transaction for "
            f"{int(s['idle_s']) // 60} min. That holds its locks and holds back vacuum.\n\n"
            f"- user={s['usename']} app={s['app']} client={s['client_addr']} "
            f"tx age={int(s['tx_age_s']) // 60} min\n"
            f"- last query (literals masked): {mask_query(s['query'])}\n"
            "- This backend was never terminated: fleet_health only reports, and terminating "
            "is your call. The usual cause is a psycopg poll loop without autocommit "
            "(scripts/bus_watch.py is the sanctioned one).\n"
            "This pages once per episode (pid + transaction start).")


def _fetch_idle_tx_sessions():
    """Impure: sessions idle in transaction, read on our own AUTOCOMMIT connection so the
    sweep never shows up as one itself."""
    with psycopg.connect(DSN, autocommit=True) as c, c.cursor() as cur:
        cur.execute(
            "SELECT pid, extract(epoch FROM now() - state_change), extract(epoch FROM xact_start), "
            "  extract(epoch FROM now() - xact_start), coalesce(usename, ''), "
            "  coalesce(nullif(application_name, ''), '(none)'), coalesce(host(client_addr), ''), "
            "  coalesce(query, '') "
            "FROM pg_stat_activity "
            "WHERE state LIKE 'idle in transaction%%' AND pid <> pg_backend_pid() "
            "  AND xact_start IS NOT NULL")
        return [{"pid": r[0], "idle_s": float(r[1]), "xact_epoch": float(r[2]),
                 "tx_age_s": float(r[3]), "usename": r[4], "app": r[5], "client_addr": r[6],
                 "query": r[7]} for r in cur.fetchall()]


def idle_in_tx_watch(dry=False):
    """Impure. Returns (warn lines, paged pids). Any failure is printed loud, never fatal."""
    import json
    import datetime
    try:
        sessions = _fetch_idle_tx_sessions()
        state = json.loads(IDLE_TX_STATE.read_text()) if IDLE_TX_STATE.exists() else {}
    except Exception as e:  # noqa: BLE001
        print(f"IDLE-IN-TX WATCH could not read pg_stat_activity/state: {type(e).__name__}: {e}")
        return [], []
    plan = idle_tx_plan(sessions, state)
    new = plan["state"]
    if plan["measure"] and not dry:
        ts = datetime.datetime.now(datetime.timezone.utc).isoformat()
        try:
            with open(IDLE_TX_MEASURE_LOG, "a", encoding="utf-8") as f:
                for s in plan["measure"]:
                    f.write(json.dumps({"ts": ts, "pid": s["pid"], "idle_s": round(s["idle_s"]),
                                        "tx_age_s": round(s["tx_age_s"]), "usename": s["usename"],
                                        "app": s["app"], "client_addr": s["client_addr"],
                                        "query": mask_query(s["query"])}) + "\n")
        except Exception as e:  # noqa: BLE001
            print(f"IDLE-IN-TX WATCH measure-log write FAILED: {type(e).__name__}: {e}")
    warns = [f"pid {s['pid']} idle in tx {int(s['idle_s']) // 60}m ({s['usename']}/{s['app']}): "
             f"{mask_query(s['query'], 60)}" for s in plan["warn"]]
    paged = []
    for s in plan["page"]:
        if dry:
            print(f"[dry] IDLE-IN-TX WATCH would page: pid {s['pid']}")
            continue
        try:
            from scripts import bus_send
            bus_send.send("cc-fleet-health", "orch-console", "blocker",
                          f"idle in transaction {int(s['idle_s']) // 60}m: pid {s['pid']} "
                          f"({s['usename']}/{s['app']})",
                          idle_tx_page_body(s), "P2")
            new[idle_tx_key(s)] = "paged"
            paged.append(s["pid"])
        except (Exception, SystemExit) as e:  # noqa: BLE001 -- unstamped, retried next sweep
            print(f"IDLE-IN-TX WATCH page FAILED for pid {s['pid']}: {type(e).__name__}: {e}")
    if not dry:
        try:
            IDLE_TX_STATE.write_text(json.dumps(new))
        except Exception as e:  # noqa: BLE001
            print(f"IDLE-IN-TX WATCH state write FAILED: {type(e).__name__}: {e}")
    return warns, paged


# 9. SCHEMA DRIFT WATCH (orch-console #80025). The operator_asks test fixture is GENERATED from
# tests/fixtures/schema/<table>.live.json (PR#584), so tests only stay as strict as prod while
# that snapshot matches live. Each sweep re-reads the live CHECKs + triggers (read-only, via
# snapshot_live_checks.read_live) and pages orch-console P2 ONCE per distinct drift; a match
# clears it, so a later drift pages again. A failed read is printed loud and never fatal; a
# failed page is not remembered, so the next sweep retries it.
SCHEMA_DRIFT_TABLES = ("operator_asks",)
SCHEMA_DRIFT_STATE = _ORCH_DIR / "logs" / "schema_drift_watch.json"


def _load_schema_snapshot(table):
    import json
    from scripts import snapshot_live_checks
    return json.loads(snapshot_live_checks.snapshot_path(table).read_text())


def schema_drift_plan(table, drift, state):
    """PURE: (page now?, new state). state maps table -> fingerprint of the drift already paged."""
    import hashlib
    new = dict(state)
    if not drift:
        new.pop(table, None)
        return False, new
    key = hashlib.sha256("\n".join(sorted(drift)).encode()).hexdigest()[:16]
    new[table] = key
    return state.get(table) != key, new


def schema_drift_watch(dry=False, read_live=None, send=None):
    """Impure. Returns tables paged. A failure here is printed loud and never fatal."""
    import json
    from scripts import snapshot_live_checks
    read_live = read_live or snapshot_live_checks.read_live
    try:
        state = json.loads(SCHEMA_DRIFT_STATE.read_text()) if SCHEMA_DRIFT_STATE.exists() else {}
    except Exception as e:  # noqa: BLE001
        print(f"SCHEMA DRIFT WATCH could not read state: {type(e).__name__}: {e}")
        state = {}
    paged = []
    for table in SCHEMA_DRIFT_TABLES:
        try:
            drift = snapshot_live_checks.diff(read_live(DSN, table), _load_schema_snapshot(table))
        except Exception as e:  # noqa: BLE001
            print(f"SCHEMA DRIFT WATCH could not read live/snapshot for {table}: {type(e).__name__}: {e}")
            continue
        page, new = schema_drift_plan(table, drift, state)
        if drift:
            print(f"SCHEMA DRIFT: live {table} != its test snapshot: " + "; ".join(drift))
        if not page:
            state = new
            continue
        if dry:
            print(f"[dry] SCHEMA DRIFT WATCH would page: {table}")
            continue
        try:
            if send is None:
                from scripts import bus_send
                send = bus_send.send
            send("cc-fleet-health", "orch-console", "blocker",
                 f"schema drift: live {table} no longer matches its test snapshot",
                 f"TL;DR: the live {table} CHECKs/triggers changed, but the test fixture is still "
                 "generated from the old snapshot, so tests now pass against a weaker table "
                 "than prod.\n\n- " + "\n- ".join(drift) + "\n\nFix: in a worktree run "
                 f"`scripts/snapshot_live_checks.py --table {table} --write`, make the tests pass, "
                 "PR it. Paged once per distinct drift; clears when live matches again.",
                 "P2", req=True)
            state = new
            paged.append(table)
        except (Exception, SystemExit) as e:  # noqa: BLE001 — unremembered, retried next sweep
            print(f"SCHEMA DRIFT WATCH page FAILED for {table}: {type(e).__name__}: {e}")
    if not dry:
        try:
            SCHEMA_DRIFT_STATE.write_text(json.dumps(state))
        except Exception as e:  # noqa: BLE001
            print(f"SCHEMA DRIFT WATCH state write FAILED: {type(e).__name__}: {e}")
    return paged


def main():
    quiet = "--quiet" in sys.argv
    sessions = live_tmux_sessions()
    with psycopg.connect(DSN) as conn, conn.cursor() as cur:
        # This sweep runs as cc-fleet-health (the fleet_health lease holder); the
        # reaper below asserts that lease, so declare our own identity here.
        cur.execute("SELECT set_config('app.current_agent_id','cc-fleet-health',true)")

        # Protected singletons — ONE source of truth (protected_agents, mig-038):
        # consulted below by offline-marking, prune, AND the drift check.
        cur.execute("SELECT agent_id FROM protected_agents")
        protected = {r[0] for r in cur.fetchall()}

        # STALE -> offline via the sanctioned reaper admin_mark_offline() (mig-037 /
        # CAI-RESP-761): a lease-gated, offline-only, audited SECDEF primitive called
        # once per agent. Replaces the old batch UPDATE, which the hardened
        # enforce_agent_status_identity trigger rejects (one GUC can't match every
        # row). Each call writes a truthful admin_offline_audit row. If our lease has
        # lapsed the call fail-closes and the txn aborts LOUD — the dead-man's switch.
        cur.execute(f"""SELECT agent_id, tmux_session FROM agent_status
                        WHERE status <> 'offline'
                          AND last_heartbeat < now() - interval '{STALE_MIN} minutes'""")
        stale_rows = cur.fetchall()
        marked, kept_alive = [], []
        for _aid, _sess in stale_rows:
            if _aid in protected:
                continue  # singleton — liveness is lease-tracked, never heartbeat-reaped
            # OBSERVED-ACTIVITY gate (re-derived #23952 / Nazim #24044): a stale heartbeat is
            # not death for an on-demand body (boot_quality.sh runs no hb loop by design). If it
            # posted a bus row within the staleness window OR has a live co-located pane, it is
            # alive despite the stale column — DON'T mark it offline (that lie says the fleet's
            # auditor is down mid-audit). Genuinely dead (no hb AND no observed activity) still
            # flips: this is observation-over-heartbeat, NOT a skip-list, so it cannot hide a
            # real death (unlike protected_agents). Window == STALE_MIN, same now() as the reaper.
            cur.execute(f"""SELECT EXISTS(SELECT 1 FROM agent_messages
                            WHERE from_agent = %s
                              AND created_at > now() - interval '{STALE_MIN} minutes')""", (_aid,))
            recent_bus = cur.fetchone()[0]
            observed, why = observed_activity(recent_bus, _sess, sessions)
            if observed:
                kept_alive.append((_aid, why))
                continue
            cur.execute("SELECT admin_mark_offline(%s, %s)",
                        (_aid, f"fleet_health sweep: stale heartbeat > {STALE_MIN}m, no observed activity"))
            if cur.fetchone()[0]:
                marked.append(_aid)

        cur.execute(f"""DELETE FROM agent_status
                        WHERE status='offline'
                          AND last_heartbeat < now() - interval '{PRUNE_DAYS} days'
                          AND agent_id <> ALL(%s)
                        RETURNING agent_id""", (list(protected),))
        pruned = [r[0] for r in cur.fetchall()]
        conn.commit()

        # 4. ARCHIVE dead-letters — mark read unread messages to gone agents.
        # "Gone" = no fresh heartbeat AND hasn't sent in SENDER_LIVE_WINDOW_H
        # (the sent-recently clause spares unregistered coordinators that never
        # write agent_status, e.g. cc-orchestrator/orch-console). Human + substrate
        # rows excluded; only messages past the ARCHIVE_MIN_AGE_H grace are swept.
        archived = []
        if "--no-archive" not in sys.argv:
            cur.execute(f"""
                UPDATE agent_messages SET read_at = now()
                WHERE read_at IS NULL
                  AND to_agent IS NOT NULL
                  AND lower(to_agent) NOT IN ({','.join("'" + a + "'" for a in sorted(_NEVER_ARCHIVE_ADDRS))})
                  AND created_at < now() - interval '{ARCHIVE_MIN_AGE_H} hours'
                  AND to_agent NOT IN (
                      SELECT DISTINCT from_agent FROM agent_messages
                      WHERE from_agent IS NOT NULL
                        AND created_at > now() - interval '{SENDER_LIVE_WINDOW_H} hours')
                  AND to_agent NOT IN (
                      SELECT agent_id FROM agent_status
                      WHERE last_heartbeat > now() - interval '{STALE_MIN} minutes')
                RETURNING to_agent""")
            archived = [r[0] for r in cur.fetchall()]
            conn.commit()

        # 5. SURFACE dead-letters to STRUCTURALLY-UNDELIVERABLE targets (audit #5B). Distinct
        # from step 4 (which reaps gone-but-once-live agents): 'musa'/'substrate' and any non
        # cc-*/cai/console address have NO possible live wake owner, so their unread NEVER
        # drains — step 4 deliberately spares them. Make them VISIBLE (one coalesced row per
        # to_agent per day to orch-console), NEVER reap.
        surfaced = surface_dead_letters(cur)
        if surfaced:
            conn.commit()

        # 6. SEQUENCE SELF-HEAL — see module docstring. Runs every sweep; a no-op
        # (zero rows touched) on every cycle where nothing has drifted. Per-table
        # errors are isolated (SAVEPOINT, bus #65719 F2) and logged, never fatal.
        seq_fixed, seq_errors = sequence_drift(cur)
        if seq_fixed:
            conn.commit()

        cur.execute("""SELECT agent_id, status, tmux_session,
                       round(extract(epoch from (now()-last_heartbeat))/60) AS m
                       FROM agent_status ORDER BY last_heartbeat DESC NULLS LAST""")
        rows = cur.fetchall()

    # reconcile against ground truth
    drift = []
    registered_sessions = set()
    for aid, status, tmux, m in rows:
        if tmux:
            registered_sessions.add(tmux)
        # Skip singletons: their tmux may live on another host (the hub runs on the
        # VPS, not this Mini) and their liveness is lease/reclaim-tracked, so a local
        # `tmux ls` miss is NOT a crash — flagging it manufactures a false alarm.
        if status == "working" and tmux and tmux not in sessions and aid not in protected:
            drift.append(f"  ! {aid}: 'working' but tmux '{tmux}' is GONE (crashed?)")
    # live CC sessions with no fresh registration (ignore the desktop 'claude' app + helpers)
    for s in sessions:
        if s not in registered_sessions and not re.match(r"^(claude|orchestrator)$", s):
            drift.append(f"  ? tmux '{s}' alive but no agent_status row points to it (unregistered/zombie)")

    # archive is a mutation — always log it (even in --quiet), it's rare + auditable
    if archived:
        from collections import Counter
        by = Counter(archived)
        print(f"archived {len(archived)} dead-letters: " +
              ", ".join(f"{a}×{n}" for a, n in by.most_common()))
    if surfaced:
        print("dead-letter SURFACED to orch-console (no live wake owner): " + ", ".join(surfaced))
    if seq_fixed:
        print("SEQUENCE SELF-HEAL — drift fixed: " +
              ", ".join(f"{t} (next was {old}, now {new})" for t, old, new in seq_fixed))
    if seq_errors:
        print("SEQUENCE SELF-HEAL — per-table errors (skipped, not fatal): " +
              ", ".join(f"{t}: {e}" for t, e in seq_errors))

    exit_paged = asks_job_exit_watch()
    if exit_paged:
        print("ASKS-JOB EXIT WATCH paged orch-console: " + ", ".join(exit_paged))

    idle_warns, idle_paged = idle_in_tx_watch()
    for w in idle_warns:
        print("IDLE-IN-TX WARN: " + w)
    if idle_paged:
        print("IDLE-IN-TX WATCH paged orch-console: pids " + ", ".join(map(str, idle_paged)))
    drift_paged = schema_drift_watch()
    if drift_paged:
        print("SCHEMA DRIFT WATCH paged orch-console: " + ", ".join(drift_paged))

    if not quiet:
        if marked:
            print("marked offline (stale heartbeat):", ", ".join(marked))
        if kept_alive:
            print("kept ONLINE despite stale heartbeat (observed activity):",
                  ", ".join(f"{a} ({why})" for a, why in kept_alive))
        if pruned:
            print("reaped (old offline rows):", ", ".join(pruned))
        print(f"live lanes: {sum(1 for r in rows if r[1]=='working')} working / {len(rows)} rows")
        for aid, status, tmux, m in rows:
            print(f"  {aid:<20} {status:<9} hb={m}m  tmux={tmux}")
        if drift:
            print("DRIFT:")
            print("\n".join(drift))
        else:
            print("no drift — DB matches live tmux")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
