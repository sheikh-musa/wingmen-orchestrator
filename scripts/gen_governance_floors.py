#!/usr/bin/env python3
"""gen_governance_floors.py — regenerate the floor LIST block in
docs/governance-floors.md from governance_floor (op#35246 Phase 1a, PR#555;
split from live status per console bus #80912/#80915).

Renders op_ref/sentence/enforced-in-code only -- no PASS/FAIL/N-of-M. Live
check status is read separately, from the governance_floor_status
boot_briefing arm, and never committed to git: a status line baked into this
doc can go stale the moment it's committed (the exact failure mode behind
console bus #80659/#80664). This block changes only when a floor is added or
retired, through a reviewed PR -- it is not meant to run on a schedule.

Same partition-on-markers mechanism as gen_data_store_registry.py: only the
block between the GENERATED markers is rewritten; everything else in the doc
(all the hand-authored prose) stays byte-for-byte untouched.
"""
from __future__ import annotations

import datetime
import os
import sys

import psycopg

sys.path.insert(0, os.path.dirname(__file__))
import bus_send  # noqa: E402 — reuse its dburl() so DSN resolution has one owner
import governance_floor_reconcile as gfr  # noqa: E402 — is_orchestrator_substrate, SUBSTRATE_SILO_REF

DOC_PATH = os.path.join(os.path.dirname(__file__), "..", "docs", "governance-floors.md")
SUBSTRATE_SILO_REF = gfr.SUBSTRATE_SILO_REF
START = "<!-- GENERATED:governance_floor:START -->"
END = "<!-- GENERATED:governance_floor:END -->"


def _source_line(is_substrate: bool) -> str:
    """Names where a PASS/FAIL came from, so a reader can never mistake
    test-DB content for a real substrate check (console bus #80664 -- the
    exact failure mode behind #80659: PR#608 shipped a real PASS from a real
    --record run against the ephemeral test harness, not the live store)."""
    now = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
    if is_substrate:
        return f"_Source: orchestrator substrate `{SUBSTRATE_SILO_REF}`, rendered {now}._"
    return (
        f"_Source: NON-SUBSTRATE DSN (test/harness), rendered {now} -- "
        "for local use only, never commit this output._"
    )


def render_table(rows: list[tuple], retired_rows: list[tuple], source_line: str) -> str:
    """Renders the floor LIST only (console bus #80912): no PASS/FAIL/N-of-M
    here -- that is live state, read separately from the governance_floor_status
    boot_briefing arm, never committed to git. This block changes only when a
    floor is added or retired, through a reviewed PR."""
    lines = [
        "| Op ref | Floor | Enforced in code |",
        "|---|---|---|",
    ]
    for op_ref, sentence, enforced_in_code in rows:
        enforced = "yes" if enforced_in_code else "no"
        lines.append(f"| {op_ref} | {sentence} | {enforced} |")
    lines.append("")
    lines.append(
        "Live PASS/FAIL/STALE status is read separately and never committed "
        "here (console bus #80912) -- query the `governance_floor_status` "
        "arm of `boot_briefing`."
    )
    lines.append("")
    if retired_rows:
        lines.append("Retired floors (lifted or withdrawn by Musa; no longer evaluated):")
        lines.append("")
        for op_ref, sentence, retired_op_ref in retired_rows:
            lines.append(f"- {op_ref} — {sentence} (retired {retired_op_ref})")
        lines.append("")
    lines.append(
        "Generated by `scripts/gen_governance_floors.py` — edit `governance_floor` "
        "(with an op# citation), not this block."
    )
    lines.append("")
    lines.append(source_line)
    return "\n".join(lines)


def main(argv=None) -> int:
    import argparse

    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dsn", default=None, help="defaults to $DATABASE_URL")
    ap.add_argument("--out", default=None,
                     help="write to this path instead of docs/governance-floors.md -- "
                          "bypasses the substrate check, for harness/test runs only")
    args = ap.parse_args(argv)

    dsn = args.dsn or bus_send.dburl(os.environ.get("DATABASE_URL"))
    is_substrate = gfr.is_orchestrator_substrate(dsn)
    out_path = args.out if args.out is not None else DOC_PATH

    if args.out is None and not is_substrate:
        sys.stderr.write(
            f"refusing to write {DOC_PATH}: this DSN is not the orchestrator substrate (no "
            f"migration_ledger row for 131_governance_floor.sql at silo {SUBSTRATE_SILO_REF!r}) "
            "-- pass --out <path> to render elsewhere for a test/harness run.\n"
        )
        return 1

    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute(
            "SELECT op_ref, sentence, enforced_in_code FROM governance_floor "
            "WHERE retired_at IS NULL ORDER BY id"
        )
        rows = cur.fetchall()

        cur.execute(
            "SELECT op_ref, sentence, retired_op_ref FROM governance_floor "
            "WHERE retired_at IS NOT NULL ORDER BY retired_at"
        )
        retired_rows = cur.fetchall()

    table = render_table(rows, retired_rows, _source_line(is_substrate))

    with open(out_path) as f:
        doc = f.read()

    if START not in doc or END not in doc:
        print(f"markers {START!r}/{END!r} not found in {out_path}", file=sys.stderr)
        return 1

    pre, _, rest = doc.partition(START)
    _, _, post = rest.partition(END)
    new_doc = f"{pre}{START}\n{table}\n{END}{post}"

    with open(out_path, "w") as f:
        f.write(new_doc)

    print(f"regenerated {len(rows)} floor rows into {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
