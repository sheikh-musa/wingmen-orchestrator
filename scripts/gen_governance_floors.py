#!/usr/bin/env python3
"""gen_governance_floors.py — regenerate the floor-rows block in
docs/governance-floors.md from governance_floor (+ its latest
governance_floor_audit check, if any) (op#35246 Phase 1a, PR#555).

Same partition-on-markers mechanism as gen_data_store_registry.py: only the
block between the GENERATED markers is rewritten; everything else in the doc
(all the hand-authored prose) stays byte-for-byte untouched. governance-floors.md
carries rulings in prose rows can't yet express -- this is additive, not a
full-file regeneration.
"""
from __future__ import annotations

import os
import sys

import psycopg

sys.path.insert(0, os.path.dirname(__file__))
import bus_send  # noqa: E402 — reuse its dburl() so DSN resolution has one owner

DOC_PATH = os.path.join(os.path.dirname(__file__), "..", "docs", "governance-floors.md")
START = "<!-- GENERATED:governance_floor:START -->"
END = "<!-- GENERATED:governance_floor:END -->"


def render_table(rows: list[tuple], retired_rows: list[tuple]) -> str:
    passing = sum(1 for _, _, _, status in rows if status == "checked_pass")
    total = len(rows)
    lines = [
        "| Op ref | Floor | Enforced in code | Last check |",
        "|---|---|---|---|",
    ]
    for op_ref, sentence, enforced_in_code, status in rows:
        enforced = "yes" if enforced_in_code else "no"
        last_check = {"checked_pass": "PASS", "checked_fail": "FAIL", None: "not yet checked"}[status]
        lines.append(f"| {op_ref} | {sentence} | {enforced} | {last_check} |")
    lines.append("")
    lines.append(f"**{passing} of {total} floors passing.**")
    lines.append("")
    if retired_rows:
        lines.append("Retired floors (lifted or withdrawn by Musa; no longer evaluated):")
        lines.append("")
        for op_ref, sentence, retired_op_ref in retired_rows:
            lines.append(f"- {op_ref} — {sentence} (retired {retired_op_ref})")
        lines.append("")
    lines.append(
        "Generated by `scripts/gen_governance_floors.py` — edit `governance_floor` "
        "(with an op# citation), not this block."
    )
    return "\n".join(lines)


def main(argv=None) -> int:
    import argparse

    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dsn", default=None, help="defaults to $DATABASE_URL")
    args = ap.parse_args(argv)

    dsn = args.dsn or bus_send.dburl(os.environ.get("DATABASE_URL"))
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute(
            """
            SELECT gf.op_ref, gf.sentence, gf.enforced_in_code, latest.event
              FROM governance_floor gf
              LEFT JOIN LATERAL (
                  SELECT event FROM governance_floor_audit
                   WHERE floor_id = gf.id AND event IN ('checked_pass', 'checked_fail')
                   ORDER BY at DESC LIMIT 1
              ) latest ON true
             WHERE gf.retired_at IS NULL
             ORDER BY gf.id
            """
        )
        rows = cur.fetchall()

        cur.execute(
            "SELECT op_ref, sentence, retired_op_ref FROM governance_floor "
            "WHERE retired_at IS NOT NULL ORDER BY retired_at"
        )
        retired_rows = cur.fetchall()

    table = render_table(rows, retired_rows)

    with open(DOC_PATH) as f:
        doc = f.read()

    if START not in doc or END not in doc:
        print(f"markers {START!r}/{END!r} not found in {DOC_PATH}", file=sys.stderr)
        return 1

    pre, _, rest = doc.partition(START)
    _, _, post = rest.partition(END)
    new_doc = f"{pre}{START}\n{table}\n{END}{post}"

    with open(DOC_PATH, "w") as f:
        f.write(new_doc)

    print(f"regenerated {len(rows)} floor rows into {DOC_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
